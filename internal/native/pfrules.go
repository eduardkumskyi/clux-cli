package native

import (
	"fmt"
	"net"
	"sort"
	"strings"
)

// Listener is one listening TCP socket from the kernel's socket table.
type Listener struct {
	IPv4, IPv6 bool   // address families the socket accepts
	Addr       net.IP // nil = wildcard
	Port       int
	UID        int
}

// maxListenerRules bounds the anchor size if the agent opens thousands of
// listeners (each costs a rule evaluation per agent packet).
const maxListenerRules = 512

// PFRules renders the com.apple/clux anchor. listeners is the current
// socket table (all users); only ports where every listener belongs to the
// agent get a loopback pass rule.
//
// Why this shape (verified on macOS 15.6 with probes as a dedicated uid):
//   - Without rules the agent reaches every loopback service (fact 5).
//   - "block out user U" + "pass in on lo0 user U keep state" blocks the
//     agent's connections to the owner's services (v4, v6, LAN address,
//     UDP) while the owner still reaches the agent's listeners: the state
//     created by the inbound SYN lets the agent's replies out.
//   - Tags set on the outbound half are gone when the packet comes back in
//     on lo0, so pf can't say "allow agent->agent, block agent->owner" by
//     itself. The agent's own listeners (sidecar preview proxy -> dev
//     server, simulator app -> dev server) are therefore opened one port at
//     a time from the socket table, by the root pf daemon.
func PFRules(agentUID, proxyPort int, listeners []Listener) string {
	var b strings.Builder
	u := agentUID
	fmt.Fprintf(&b, "# clux native: network policy for the agent user (uid %d).\n", u)
	b.WriteString("# Generated by `clux native`; changes are overwritten.\n")
	b.WriteString("# The owner's egress proxy is the only way out.\n")
	fmt.Fprintf(&b, "pass out quick on lo0 inet proto tcp from any to 127.0.0.1 port %d user %d flags S/SA keep state\n", proxyPort, u)
	fmt.Fprintf(&b, "pass out quick on lo0 inet6 proto tcp from any to ::1 port %d user %d flags S/SA keep state\n", proxyPort, u)

	v4, v6 := agentLoopbackPorts(agentUID, proxyPort, listeners)
	if len(v4)+len(v6) > 0 {
		b.WriteString("# The agent's own loopback listeners (kept current by the pf daemon).\n")
	}
	n := 0
	for _, p := range v4 {
		if n++; n > maxListenerRules {
			break
		}
		fmt.Fprintf(&b, "pass out quick on lo0 inet proto tcp from any to 127.0.0.1 port %d user %d flags S/SA keep state\n", p, u)
	}
	for _, p := range v6 {
		if n++; n > maxListenerRules {
			break
		}
		fmt.Fprintf(&b, "pass out quick on lo0 inet6 proto tcp from any to ::1 port %d user %d flags S/SA keep state\n", p, u)
	}

	b.WriteString("# Connections to the agent's listeners (host agent -> sidecar, previews);\n")
	b.WriteString("# their state lets the agent's replies out past the block below.\n")
	fmt.Fprintf(&b, "pass in quick on lo0 proto tcp from any to any user %d flags S/SA keep state\n", u)
	b.WriteString("# Everything else the agent sends: refused, IPv4 and IPv6 alike\n")
	b.WriteString("# (without a family pf would expand to inet only).\n")
	fmt.Fprintf(&b, "block return out quick inet proto { tcp udp } from any to any user %d\n", u)
	fmt.Fprintf(&b, "block return out quick inet6 proto { tcp udp } from any to any user %d\n", u)
	return b.String()
}

// agentLoopbackPorts returns the sorted ports (per family) that the agent
// may connect to on loopback: it listens there on loopback or wildcard, and
// nobody else listens on that port in any family (a second listener could
// be a more specific bind that would receive the agent's connection).
func agentLoopbackPorts(agentUID, proxyPort int, listeners []Listener) (v4, v6 []int) {
	foreign := map[int]bool{}
	for _, l := range listeners {
		if l.UID != agentUID {
			foreign[l.Port] = true
		}
	}
	s4, s6 := map[int]bool{}, map[int]bool{}
	for _, l := range listeners {
		if l.UID != agentUID || foreign[l.Port] || l.Port == proxyPort || l.Port <= 0 || l.Port > 65535 {
			continue
		}
		wild := l.Addr == nil || l.Addr.IsUnspecified()
		if l.IPv4 && (wild || l.Addr.Equal(net.IPv4(127, 0, 0, 1))) {
			s4[l.Port] = true
		}
		if l.IPv6 && (wild || l.Addr.Equal(net.IPv6loopback)) {
			s6[l.Port] = true
		}
	}
	return sortedKeys(s4), sortedKeys(s6)
}

func sortedKeys(m map[int]bool) []int {
	out := make([]int, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Ints(out)
	return out
}
