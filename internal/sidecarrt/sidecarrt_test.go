func TestPruneKeepsRecentAndInUse(t *testing.T) {
	i := &Installer{Root: t.TempDir(), Keep: 2}
	base := time.Now().Add(-time.Hour)
	for n, v := range []string{"v1", "v2", "v3", "v4"} {
		d := filepath.Join(i.Root, "sidecar", v)
		os.MkdirAll(d, 0o755)
		f := filepath.Join(d, readyFile)
		os.WriteFile(f, []byte("{}"), 0o644)
		ts := base.Add(time.Duration(n) * time.Minute)
		os.Chtimes(f, ts, ts)
	}
	i.prune([]string{"v1"})
	for v, want := range map[string]bool{"v1": true, "v2": false, "v3": true, "v4": true} {
		_, err := os.Stat(filepath.Join(i.Root, "sidecar", v))
		if (err == nil) != want {
			t.Errorf("%s kept=%v, want %v", v, err == nil, want)
		}
	}
}

func TestBundleFromFrame(t *testing.T) {
	good := map[string]any{"version": "1a2b3c", "sha256": strings.Repeat("A", 64), "url": "https://api.clux.space/api/byoc/sidecar-bundle/1a2b3c"}
	b, err := BundleFromFrame(good)
	if err != nil || b.SHA256 != strings.Repeat("a", 64) {
		t.Fatalf("%+v %v", b, err)
	}
	for _, bad := range []map[string]any{
		nil,
		{"version": "../x", "sha256": strings.Repeat("a", 64), "url": "https://x"},
		{"version": "v", "sha256": "abc", "url": "https://x"},
		{"version": "v", "sha256": strings.Repeat("a", 64), "url": "http://example.com/b"},
		{"version": "v", "sha256": strings.Repeat("z", 64), "url": "https://x"},
	} {
		var v any
		if bad != nil {
			v = bad
		}
		if _, err := BundleFromFrame(v); err == nil {
			t.Errorf("accepted %v", bad)
		}
	}
	if _, err := BundleFromFrame(map[string]any{"version": "v", "sha256": strings.Repeat("a", 64), "url": "http://localhost:8009/b"}); err != nil {
		t.Errorf("local dev backend rejected: %v", err)
	}
}
